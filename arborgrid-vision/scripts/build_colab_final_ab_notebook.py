            "    def __init__(self, pos_weights=(1.2, 8.0, 5.0)):\n",
            "        super().__init__()\n",
            "        self.register_buffer(\"pw\", torch.tensor(pos_weights, dtype=torch.float32).view(1, 3, 1, 1))\n",
