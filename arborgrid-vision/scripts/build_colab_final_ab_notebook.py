            "        denom = p.sum(dim=(0, 2, 3)) + targets.sum(dim=(0, 2, 3)) + 1.0\n",
            "        dice_c = 1.0 - (2.0 * inter + 1.0) / denom\n",
            "        dice = 0.25 * dice_c[0] + 0.50 * dice_c[1] + 0.25 * dice_c[2]\n",
